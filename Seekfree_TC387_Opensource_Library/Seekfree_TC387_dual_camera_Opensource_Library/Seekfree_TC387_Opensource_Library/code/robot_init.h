/*********************************************************************************************************************
 * @file        robot_init.h
 * @brief       机器人系统初始化与控制主循环入口
 * @note        集中管理所有子模块的初始化与 PIT 中断中的控制环调用
 ********************************************************************************************************************/
#ifndef _ROBOT_INIT_H_
#define _ROBOT_INIT_H_

#include "robot_config.h"

// ============================================================================
//  调试模式选择 —— 仅启用需要调试的模块，其他模块跳过
//  在调试阶段可以通过注释/取消注释来选择性启用
// ============================================================================
#define DEBUG_MODE_IMU_ONLY     (0)     // 1 = 仅调试 IMU（不使能电机与平衡）
                                        // 0 = 完整控制模式

// ============================================================================
//  公开函数
// ============================================================================

/**
 * @brief   机器人系统初始化（在 core0_main 中调用）
 *          根据调试模式选择性初始化各模块
 */
void Robot_System_Init(void);

/**
 * @brief   机器人控制主循环（在 PIT 中断中调用）
 *          5ms 周期执行 IMU 读取 → 编码器更新 → 平衡控制 → 调试输出
 */
void Robot_Control_Loop(void);

#endif // _ROBOT_INIT_H_
