/*********************************************************************************************************************
 * @file        robot_config.h
 * @brief       轮腿机器人全局配置文件 —— 引脚分配、物理参数、控制周期等
 * @note        所有模块的硬件引脚与关键参数统一在此定义，便于移植与维护
 *
 *  ======================== 引脚总览 (基于推荐IO分配) ========================
 *
 *  [Boot 禁止引脚] P14_2 P14_3 P14_4 P14_5 P14_6 P10_5 P10_6
 *
 *  [摄像头1 已占用] P00_0~P00_7(数据), P02_0(VSY), P02_1(PCLK),
 *                   P02_2(RX), P02_3(TX)
 *
 *  [IMU SPI0 已占用] P20_11(SCK) P20_14(MOSI) P20_12(MISO) P20_13(CS)
 *                    — 由库内 zf_device_imu660ra.h 定义
 *
 *  [PWM 可用 8路]    P21_2 P21_3 P21_4 P21_5 P02_4 P02_5 P02_6 P02_7
 *
 *  [编码器 可用 4组]
 *     TIM2: P33_7 / P33_6     TIM4: P02_8 / P00_9
 *     TIM5: P10_3 / P10_1     TIM6: P20_3 / P20_0
 *
 *  [TFT屏幕 SPI2]   P15_3(SCK) P15_5(MOSI) P15_4(BL)
 *                    P15_2(CS) P15_1(RST) P15_0(DC)
 *
 *  [舵机]            P33_9
 *  [蜂鸣器]          P33_10
 *
 *  [串口预留]        UART1: P15_6(TX) P15_7(RX)  — 可接蓝牙/ROS
 *                    UART3: P20_10(TX 备选) P20_9(RX 备选)
 *
 ********************************************************************************************************************/
