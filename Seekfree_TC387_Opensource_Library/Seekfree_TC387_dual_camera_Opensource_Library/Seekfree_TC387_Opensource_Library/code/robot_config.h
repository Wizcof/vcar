// ============================================================================
//  系统控制周期 (单位：微秒)
// ============================================================================
#define CONTROL_PERIOD_US           (5000)          // 主控制环 5ms => 200Hz
#define CONTROL_PERIOD_S            (0.005f)        // 同上，秒为单位，供算法使用
#define CONTROL_PIT_CH              (CCU60_CH0)     // 控制环使用的 PIT 通道

// ============================================================================
//  IMU 相关
// ============================================================================
// IMU660RA 引脚由库内 zf_device_imu660ra.h 默认定义:
//   SPI0: SCK=P20_11  MOSI=P20_14  MISO=P20_12  CS=P20_13
// 如需切换 IMU 型号，修改此宏并替换对应 init/get 函数即可
#define IMU_USE_IMU660RA            (1)             // 1 = 使用 IMU660RA

// ============================================================================
//  电机 PWM 输出引脚 (双路直流有刷 / 轮毂电机)
//  每个电机需要 2 路 PWM: PWM_A 正转 / PWM_B 反转 (H桥驱动)
//  参考推荐IO: 8路PWM = P21_2 P21_3 P21_4 P21_5 P02_4 P02_5 P02_6 P02_7
//  注：若启用无刷串口驱动，保留定义以兼容。
// ============================================================================
#define MOTOR_PWM_FREQ              (17000)         // 17kHz，超出人耳范围减少啸叫

// ---- 左电机 (推荐IO: P21_2 / P21_3) ----
#define MOTOR_L_PWM_A               (ATOM0_CH0_P21_2)
#define MOTOR_L_PWM_B               (ATOM0_CH1_P21_3)

// ---- 右电机 (推荐IO: P21_4 / P21_5) ----
#define MOTOR_R_PWM_A               (ATOM0_CH2_P21_4)
#define MOTOR_R_PWM_B               (ATOM0_CH3_P21_5)

// ============================================================================
//  无刷驱动拨盘串口通信定义 (CYT2BL3 无刷双驱串口协议)
//  推荐IO: UART3 P15_7(RX) / P15_6(TX)
// ============================================================================
#define MOTOR_USE_BRUSHLESS_UART    (1)             // 1:使用无刷串口, 0:使用PWM有刷
#define MOTOR_UART                  (UART_3)        // 无刷电机通讯串口
#define MOTOR_BAUDRATE              (460800)        // 波特率 (CYT2BL3 默认)
#define MOTOR_UART_RX               (UART3_RX_P15_7)// 接收引脚
#define MOTOR_UART_TX               (UART3_TX_P15_6)// 发送引脚


// ============================================================================
//  编码器引脚 (正交编码器)
//  推荐IO 4组编码器:
//    TIM2: LSB=P33_7 DIR=P33_6
//    TIM4: LSB=P02_8 DIR=P00_9  (注意: 摄像头2可能占用P02_8)
//    TIM5: LSB=P10_3 DIR=P10_1  ← 使用
//    TIM6: LSB=P20_3 DIR=P20_0  ← 使用
// ============================================================================
// ---- 左编码器 (TIM5: P10_3 / P10_1) ----
#define ENCODER_L                   (TIM5_ENCODER)
#define ENCODER_L_CH1               (TIM5_ENCODER_CH1_P10_3)
#define ENCODER_L_CH2               (TIM5_ENCODER_CH2_P10_1)

// ---- 右编码器 (TIM6: P20_3 / P20_0) ----
#define ENCODER_R                   (TIM6_ENCODER)
#define ENCODER_R_CH1               (TIM6_ENCODER_CH1_P20_3)
#define ENCODER_R_CH2               (TIM6_ENCODER_CH2_P20_0)

